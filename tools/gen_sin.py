"""Generates src/sim/sin_table.h: quarter sine, 1025 entries, Q12."""
import math
import pathlib

values = [round(math.sin(i / 1024 * math.pi / 2) * 4096) for i in range(1025)]
rows = [", ".join(map(str, values[i:i + 16])) for i in range(0, 1025, 16)]
out = pathlib.Path(__file__).parent.parent / "src/sim/sin_table.h"
out.write_text("/* Generated by tools/gen_sin.py */\nstatic const short SIN_Q[1025] = {\n" + ",\n".join(rows) + "\n};\n")
